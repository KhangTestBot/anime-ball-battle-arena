export const CHARACTER_ROSTER: readonly CharacterConfig[] = [
  ...RAW_ROSTER,
  ...EXPANSION_RAW_ROSTER,
].map((raw) => ({
  ...raw,
  skills: CHARACTER_SKILLS[raw.id] ?? [],
  ultimate: CHARACTER_ULTIMATES[raw.id] ?? {
    name: `${raw.name.toUpperCase()} OVERDRIVE`,
    desc: 'Unleashes a devastating signature ultimate attack across the entire arena.',
    voiceLine: `${raw.name}! Full power!`,
    voicePitch: 1.0,
    voiceRate: 1.05,
    voiceGender: 'neutral',
    archetype: 'mega-shockwave',
    color: raw.primaryColor,
  },
}));

export const CHARACTER_MAP: ReadonlyMap<string, CharacterConfig> = new Map(
  CHARACTER_ROSTER.map((char) => [char.id, char]),
);

export function getCharacterById(id: string): CharacterConfig {
  const found = CHARACTER_MAP.get(id);
  if (!found) {
    return CHARACTER_ROSTER[0];
  }
  return found;
}
